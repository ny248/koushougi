def get_piece_value(piece_id: int) -> int:
    """駒の価値を取得"""
    return PIECE_VALUES.get(piece_id, 0)


def get_promotion_value(piece_id: int) -> int:
    """成った時の価値上昇を取得

    成り先はbackend/domain/piece_registryから取得（二重管理を避ける）
    """
    from backend.domain.piece_registry import get_piece

    piece = get_piece(piece_id)
    if piece.promotes_to is None:
        return 0

    return PIECE_VALUES.get(piece.promotes_to, 0) - PIECE_VALUES.get(piece_id, 0)
